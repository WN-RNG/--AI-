export function translateUi(
  language: Language,
  source: string,
  values?: TranslationValues,
): string {
  const dictionary = language === 'en' ? english : chinese;
  const exact = Object.prototype.hasOwnProperty.call(dictionary, source);
  const trimmed = source.trim();
  const translated = exact
    ? dictionary[source]
    : Object.prototype.hasOwnProperty.call(dictionary, trimmed)
      ? source.replace(trimmed, () => dictionary[trimmed])
      : translateStatusError(language, source);
  return values
    ? translated.replace(/\{(\w+)\}/g, (token, key: string) =>
        Object.prototype.hasOwnProperty.call(values, key) ? String(values[key]) : token,
      )
    : translated;
}

// Only known service-error envelopes are formatted; no filenames or photo captions are inspected.
function translateStatusError(language: Language, source: string): string {
  if (language !== 'en') return source;
  let match = /^服务响应格式异常（(\d{3})），请稍后重试$/.exec(source);
  if (match) return `Unexpected response format (${match[1]}). Please try again.`;
  match = /^请求失败（(\d{3})）$/.exec(source);
  if (match) return `Request failed (${match[1]}).`;
  match = /^下载失败（(\d{3})），请稍后重试$/.exec(source);
  if (match) return `Download failed (${match[1]}). Please try again.`;
  return source;
}

/** Translate a known upload error suffix without interpreting or rewriting its filename prefix. */
export function translateUploadIssue(language: Language, issue: string): string {
  const knownReasons = [
    '仅支持 JPG、PNG 或 WebP 图片，已跳过',
    '超过 30MB，已跳过',
    '图片无法读取，请确认格式正确且文件完整',
    '图片尺寸过大，请控制在 8000 万像素以内',
    '仅支持静态 JPG、PNG、WebP 图片',
    '单张照片不能超过 30MB',
    '超过 20MB 的照片需要确认后才能上传',
    '图片处理繁忙，请稍后重试',
    '上传失败，请重试',
    '上传失败',
    '连接中断，请先检查上传结果，再重试未完成的照片',
    '上传超时，请先检查上传结果，再重试未完成的照片',
  ];
  if (language === 'en') {
    for (const reason of knownReasons) {
      const suffix = `：${reason}`;
      if (issue.endsWith(suffix)) {
        return `${issue.slice(0, -suffix.length)}: ${translateUi(language, reason)}`;
      }
    }
  }
  return translateUi(language, issue);
}
